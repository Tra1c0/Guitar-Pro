#!/usr/bin/env python3
"""Generate executable capabilities and the parity table from one reviewed specification."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'core/capabilities/src/main/kotlin/dev/riffworkbench/capabilities/FeatureRegistry.kt'
MATRIX = ROOT / 'docs/PARITY.md'

def outputs():
    spec = json.loads((ROOT / 'spec/features.json').read_text())
    lines = []
    table = ['# Paritätsmatrix', '', 'Generiert aus `spec/features.json`. `IMPLEMENTED` bezieht sich auf den ausdrücklich beschriebenen Phase-1-Umfang. Teilweise vorhandene Eingaben sind im Namen und Vertragsumfang eingegrenzt; ein Modell allein gilt nicht als fertige Bearbeitung oder Klangerzeugung.', '', '## GP-Dateitreue', '', 'GP3/4/5, GPX und GP7/8 sind in Phase 1 in allen fünf Fähigkeiten noch nicht freigegeben. GP7-Rückexport und GP8-spezifische Treue werden getrennt verifiziert. Native Speicherung einer Eigenschaft ist kein GP-Fidelity-Nachweis.', '', '## Anwendungskern und Austausch', '', 'Lesen/Darstellen/Bearbeiten beschreiben den eigenen Anwendungskern, soweit implementiert. Formatzeilen benennen die jeweilige Import-/Exportgrenze. Nur das native Format ist aktuell ausgegeben. Nicht freigegebene Merkmals-/Formatkombinationen bleiben offen; native Bewahrung ist separat durch den vollständigen Projekt-Roundtrip abgedeckt.', '', 'Verifikation `AUTOMATED` bezeichnet lokale JVM-/Robolectric-Tests für den beschriebenen Teilumfang. Geräte-, Hör-, GP8- und Cubase-Abnahmen sind separat offen.', '', '| ID | Funktion | Lesen | Darstellen | Bearbeiten | Playback | Export | Etappe | Vertrag | Prüfung |', '|---|---|---|---|---|---|---|---|---|---|']
    for f in spec['features']:
        fields = ', '.join(json.dumps(f[k], ensure_ascii=False) for k in ('id', 'labelDe', 'labelEn', 'group', 'groupDe', 'route'))
        dimensions = ', '.join(f'Dimension.{d} to ImplementationStatus.{s}' for d, s in f['dimensions'].items())
        lines.append(f'        Feature({fields}, Milestone.{f["stage"]}, {json.dumps(f["contractId"])}, mapOf({dimensions}), Verification.{f["verification"]})')
        table.append('| ' + ' | '.join([f['id'], f['labelDe'], *f['dimensions'].values(), f['stage'], f'[{f["contractId"]}](CONTRACTS.md#{f["contractId"].lower()})', f['verification']]) + ' |')
    source = '// Generated by tools/generate_registry.py from spec/features.json. Do not edit.\npackage dev.riffworkbench.capabilities\n\nobject FeatureRegistry {\n    val all: List<Feature> = listOf(\n' + ',\n'.join(lines) + '\n    )\n    fun group(id: String) = all.filter { it.group == id }\n    fun find(id: String) = all.firstOrNull { it.id == id }\n}\n'
    return {TARGET: source, MATRIX: '\n'.join(table) + '\n'}

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Out of date: {path.relative_to(ROOT)}; run python3 tools/generate_registry.py')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
